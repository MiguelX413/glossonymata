#!/usr/bin/env python3
"""Validate pinned inputs and regenerate Rust lookup and coverage (stdlib only)."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def parse_registry(text):
    """Preserve repeated fields and unfold registry continuation lines."""
    records = []
    for block in text.split('%%'):
        fields = {}
        key = None
        for line in block.strip().splitlines():
            if line.startswith(' ') and key:
                fields[key][-1] += ' ' + line.strip()
            else:
                key, value = line.split(': ', 1)
                fields.setdefault(key, []).append(value)
        if fields.get('Type') == ['language']:
            records.append(fields)
    return records


def exclusion(record):
    if '..' in record['Subtag'][0]:
        return 'private_use_range'
    if 'Deprecated' in record:
        return 'deprecated'
    if record.get('Scope') == ['collection']:
        return 'collection'
    if record.get('Scope') == ['special']:
        return 'special'
    return None


def validate(data, registry):
    if data.get('schema_version') != 2:
        raise ValueError('unsupported endonyms schema version')
    sources = data['sources']
    for key, source in sources.items():
        if not source.get('reference') or not source.get('description'):
            raise ValueError(f'{key}: source needs reference and description')
    by_code = {}
    for entry in data['languages']:
        if set(entry) != {'code', 'endonym', 'sources'}:
            raise ValueError('language records require only code, endonym, and sources')
        code = entry['code']
        if code in by_code:
            raise ValueError(f'{code}: duplicate language')
        if code not in registry or exclusion(registry[code]):
            raise ValueError(f'{code}: not an eligible registered language')
        value = entry['endonym']
        if (not isinstance(value, str) or not value.strip() or value != value.strip()
                or any(ord(c) < 32 for c in value)):
            raise ValueError(f'{code}: invalid endonym')
        refs = entry['sources']
        if (not isinstance(refs, list) or not refs
                or any(not isinstance(ref, str) or ref not in sources for ref in refs)):
            raise ValueError(f'{code}: endonym needs known sources')
        by_code[code] = entry
    return by_code


def rust_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(raw, metadata, data):
    if hashlib.sha256(raw).hexdigest() != metadata['sha256']:
        raise ValueError('registry checksum differs from data/registry.json')
    text = raw.decode('utf-8')
    if text.splitlines()[0] != 'File-Date: ' + metadata['file_date']:
        raise ValueError('registry date differs from metadata')
    records = parse_registry(text)
    registry = {r['Subtag'][0]: r for r in records}
    if len(registry) != len(records):
        raise ValueError('duplicate registry language subtag')
    entries = validate(data, registry)
    rows = []
    lookup = []
    for code, record in sorted(registry.items()):
        excluded = exclusion(record)
        available = code in entries
        row = {'code': code, 'descriptions': record['Description'],
               'scope': record.get('Scope', ['individual'])[0],
               'excluded': excluded,
               'lookup_available': available}
        if 'Preferred-Value' in record:
            row['preferred_value'] = record['Preferred-Value'][0]
        rows.append(row)
        if available:
            lookup.append(f'        {rust_string(code)} => {rust_string(entries[code]["endonym"])},')
    eligible = sum(r['excluded'] is None for r in rows)
    missing = eligible - len(lookup)
    exclusions = Counter(r['excluded'] for r in rows if r['excluded'])
    report = {'registry_date': metadata['file_date'], 'language_records': len(rows),
              'eligible_languages': eligible, 'missing_endonyms': missing,
              'exclusions': dict(sorted(exclusions.items())), 'lookup_entries': len(lookup),
              'records': rows}
    rust = '// Generated by scripts/generate.py. Do not edit.\n\npub(super) fn lookup(code: &str) -> Option<&\'static str> {\n    Some(match code {\n' + '\n'.join(lookup) + '\n        _ => return None,\n    })\n}\n'
    md = f'''<!-- Generated by scripts/generate.py. Do not edit. -->
# Coverage

IANA snapshot: **{metadata['file_date']}**. All **{len(rows)}** `Type: language`
records are accounted for; ranges count as one registry record, not individual codes.
There are **{eligible}** eligible language subtags and **{len(lookup)}** lookup entries.

| Coverage | Languages |
| --- | ---: |
| Preferred endonym selected | {len(lookup)} |
| Missing endonym | {missing} |

| Exclusion | Registry records |
| --- | ---: |
'''
    for reason, count in sorted(exclusions.items()):
        md += f'| {reason} | {count} |\n'
    md += '''
See [coverage.json](coverage.json) for every language, description, exclusion,
preferred replacement where recorded, and lookup availability.
Filter `excluded == null` and `lookup_available == false` to find missing endonyms.

Each supplied name is the project's preferred spelling, including any chosen
vowel points, macrons, or accent marks. References document those choices;
there are no verification tiers or review gates. A missing entry only means
that a preferred endonym has not been selected yet. Macrolanguages remain
eligible. Collections, special codes, deprecated subtags, and private-use ranges
are excluded. Deprecated codes are reported, not automatically redirected.
'''
    return {'src/generated.rs': rust, 'data/coverage.json': json.dumps(report, ensure_ascii=False, indent=2) + '\n', 'data/coverage.md': md}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated files are stale')
    args = parser.parse_args()
    try:
        outputs = render((ROOT / 'data/language-subtag-registry.txt').read_bytes(),
                         json.loads((ROOT / 'data/registry.json').read_text()),
                         json.loads((ROOT / 'data/endonyms.json').read_text()))
        stale = []
        for name, content in outputs.items():
            path = ROOT / name
            if args.check:
                if not path.exists() or path.read_text() != content:
                    stale.append(name)
            else:
                path.write_text(content)
        if stale:
            raise ValueError('stale generated files: ' + ', '.join(stale))
    except (ValueError, KeyError, TypeError) as error:
        print(f'generation failed: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
